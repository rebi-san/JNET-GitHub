-- Notes:  Defines the MeshResourceListGen function, which takes a string of
--         space-delimited decoration mesh instance files and prints the con-
--         tents of a resource list file that will load all the necessary
--         meshes.
--
-- Author: John Edwards
-- Date C: 6-26-2008
-------------------------------------------------------------------------------

local function CountMeshes( decoTbl )
	local accumTbl = {}

	for i,deco in ipairs( decoTbl ) do
		if type( deco ) == "table" then
			if accumTbl[ deco.Mesh ] then
				accumTbl[ deco.Mesh ] = accumTbl[ deco.Mesh ] + 1
			else
				accumTbl[ deco.Mesh ] = 1
			end
		end
	end

	return accumTbl
end

local function FindMaxMeshUsage( accumTblTbl )
	local maxAccumTbl = {}

	for i = 1,#accumTblTbl do
		local accumTbl = accumTblTbl[ i ]

		for name,accum in pairs( accumTbl ) do
			local maxAccum = accum
			if maxAccumTbl[ name ] then maxAccum = math.max( maxAccum, maxAccumTbl[ name ] ) end
			maxAccumTbl[ name ] = maxAccum
		end
	end

	return maxAccumTbl
end

local function PrintAccumTbl( accumTbl )
	resourceTable = {}

	dofile( "../Code/Base/Resource.lua" )
	dofile( "Data/Resources/Meshes.lua.bak" )
	
	-- Build a wad map from the resources file
	local meshWadMap = {}
	for i,res in ipairs( resourceTable ) do
		if res.class == "MeshWad" then
			for n = 0,15 do
				local name = res[ "name"..n ]
				if name ~= nil then
					meshWadMap[ name ] = res.name
				end
			end
		end
	end
	
	-- Sort the accum table.
	local sorter = {}
	for name,accum in pairs( accumTbl ) do
		table.insert( sorter, { name = name, accum = accum } )
	end
	table.sort( sorter, function( t1, t2 ) return t1.name < t2.name end )
	
	-- Build the mesh wad table
	local meshWads = {}
	local meshesToAdd = {}
	for i,tbl in ipairs( sorter ) do
		local name = tbl.name
		local wadName = meshWadMap[ name ]
		if wadName ~= nil then
			local wadNum = string.gsub( wadName, "MeshWad", "" )
			wadNum = tonumber( wadNum )
			if meshWads[ wadNum ] == nil then meshWads[ wadNum ] = {} end
			table.insert( meshWads[ wadNum ], tbl )
		else 
			table.insert( meshesToAdd, tbl ) 
		end
	end
		
	-- Add the new meshes
	local kMaxMeshesInWad = 16
	local lastWad = meshWads[ table.getn( meshWads ) ]
	for i,tbl in ipairs( meshesToAdd ) do
		if lastWad == nil or table.getn( lastWad ) > ( kMaxMeshesInWad - 1 ) then
			lastWad = {}
			table.insert( meshWads, lastWad )
		end
		table.insert( lastWad, tbl )
	end
	
	-- Write to file
	for i,wad in ipairs( meshWads ) do
		print( 'wad "MeshWad" "MeshWad'..i..'"' )
		for n,tbl in ipairs( wad ) do
			if n == 1 then 
				print( '{ wadresource "Mesh" "'..tbl.name..'" '..
					'{ source = "'..tbl.name..'.PSSG", instanceLimit = '..tbl.accum..' }' )
			else
				print( ', wadresource "Mesh" "'..tbl.name..'" '..
					'{ source = "'..tbl.name..'.PSSG", instanceLimit = '..tbl.accum..' }' )
			end
		end
		print( '}' )
	end
end

function MeshResourceListGen( decoFileList )
	local accumTblTbl = {}

	for file in decoFileList:gmatch( "%S+" ) do
		dofile( file )
		local accumTbl = CountMeshes( DecorationMeshInstances )
		table.insert( accumTblTbl, accumTbl )
	end

	local maxAccumTbl = FindMaxMeshUsage( accumTblTbl )
	
	print( "-- THIS FILE IS AUTOMATICALLY GENERATED.\n-- DO NOT MODIFY THIS FILE!" )
	PrintAccumTbl( maxAccumTbl )
end
